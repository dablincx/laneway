//! Generates the env var reference and `.env.example` from [`SETTINGS`].

use std::fmt::Write;

use crate::{Area, SETTINGS, Setting};

const HEADER: &str = "<!-- generated by `laneway config docs`, don't edit by hand -->";

/// Markdown for `docs/configuration/environment-variables.md`.
pub fn render_markdown() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}\n");
    out.push_str("# Environment variables\n\n");
    out.push_str(
        "Every laneway setting can be set with an env var. Env vars win over settings saved in the \
         UI (the field then shows as locked). Secrets also accept a `_FILE` variant that reads the \
         value from a file, e.g. for Docker secrets. Empty values count as unset.\n\n",
    );
    out.push_str("Invalid values stop laneway at startup with a message naming the variable.\n\n");

    for area in Area::ALL {
        let settings: Vec<&Setting> = SETTINGS.iter().filter(|s| s.area == *area).collect();
        if settings.is_empty() {
            continue;
        }
        let _ = writeln!(out, "## {}\n", area.title());
        out.push_str("| Variable | Type | Default | Description |\n|---|---|---|---|\n");
        for s in settings {
            let default = match s.default {
                Some(d) => format!("`{d}`"),
                None if s.required => "**required**".to_owned(),
                None => "*(unset)*".to_owned(),
            };
            let mut description = escape(&s.description());
            if s.secret {
                let _ = write!(description, " Secret, also accepts `{}_FILE`.", s.env);
            }
            let _ = write!(description, " Example: `{}`", s.example);
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} |",
                s.env,
                escape(&s.kind.describe()),
                default,
                description
            );
        }
        out.push('\n');
    }
    out
}

/// Content of `examples/.env.example`.
pub fn render_env_example() -> String {
    let mut out = String::new();
    out.push_str("# laneway example env file, generated by `laneway config docs`, don't edit by hand.\n");
    out.push_str("# Full reference: docs/configuration/environment-variables.md\n");
    out.push_str("# Required vars are uncommented. Everything else shows its default.\n");

    for area in Area::ALL {
        let settings: Vec<&Setting> = SETTINGS.iter().filter(|s| s.area == *area).collect();
        if settings.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n# --- {} ---", area.title());
        for s in settings {
            let _ = writeln!(out, "\n# {}", s.description());
            let mut meta = format!("# type: {}", s.kind.describe().replace('`', ""));
            if s.secret {
                let _ = write!(meta, ", secret (or {}_FILE)", s.env);
            }
            let _ = writeln!(out, "{meta}");
            if s.required {
                let _ = writeln!(out, "{}={}", s.env, s.example);
            } else {
                let _ = writeln!(out, "#{}={}", s.env, s.default.unwrap_or(s.example));
            }
        }
    }
    out
}

fn escape(text: &str) -> String {
    text.replace('|', "\\|")
}
