//! The `laneway` binary: web app + API, background worker, and maintenance commands.

mod cli;
mod http;
mod logging;
mod settings;
mod worker;

use std::process::ExitCode;

use clap::Parser;

#[tokio::main]
async fn main() -> ExitCode {
    let cli = cli::Cli::parse();
    match cli::run(cli).await {
        Ok(code) => code,
        Err(err) => {
            eprintln!("error: {err:#}");
            ExitCode::FAILURE
        }
    }
}
